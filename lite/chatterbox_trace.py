"""Optional private local trace of Nano native inference.

Enable only by setting NANO_INFERENCE_TRACE_DIR before launching the Nano service.
The trace contains complete supplied narration. Raw WAV snapshots additionally
require NANO_INFERENCE_TRACE_SAVE_WAV=1. Never log reference voice audio, paths,
authorization headers, or cancellation tokens.
"""
from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import threading
from typing import Any

_WRITE_LOCK = threading.Lock()


def _directory() -> Path | None:
    raw = os.environ.get("NANO_INFERENCE_TRACE_DIR", "").strip()
    return Path(raw).expanduser() if raw else None


def record(event: str, *, trace_id: str, **fields: Any) -> None:
    """JSONL diagnostic only: never change generation on logging failure."""
    directory = _directory()
    if directory is None:
        return
    try:
        payload = {
            "timestamp_utc": datetime.now(timezone.utc).isoformat(timespec="milliseconds"),
            "process_id": os.getpid(),
            "trace_id": trace_id,
            "event": event,
            **fields,
        }
        line = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n"
        with _WRITE_LOCK:
            directory.mkdir(parents=True, exist_ok=True)
            fd = os.open(str(directory / "nano_native_trace.jsonl"),
                         os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600)
            with os.fdopen(fd, "a", encoding="utf-8") as stream:
                stream.write(line)
    except (OSError, TypeError, ValueError):
        return


def wav_snapshot(data: bytes, *, trace_id: str, chunk_index: int, stage: str) -> str | None:
    """Only when explicitly requested, store WAV for exact listening comparison.

    Trace ID is always generated by the Nano service; stage is constrained.
    """
    directory = _directory()
    if directory is None or os.environ.get("NANO_INFERENCE_TRACE_SAVE_WAV") != "1":
        return None
    if stage not in {"native", "after_atempo", "final"}:
        return None
    if not isinstance(data, bytes) or not data.startswith(b"RIFF"):
        return None
    if (len(trace_id) != 24 or any(ch not in "0123456789abcdef" for ch in trace_id)
            or not 0 <= chunk_index <= 9999):
        return None
    filename = f"{trace_id}_chunk{chunk_index:04d}_{stage}.wav"
    try:
        with _WRITE_LOCK:
            directory.mkdir(parents=True, exist_ok=True)
            fd = os.open(str(directory / filename),
                         os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "wb") as stream:
                stream.write(data)
        return filename
    except OSError:
        return None


def wav_sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
